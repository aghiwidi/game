export function getBuildingCost(type: BuildingType, faction: FactionId): Partial<Resources> {
  const base = BUILDING_DEFS[type].cost;
  if (faction === 'byzantium' && (type === 'wall' || type === 'gate')) {
    return {
      ...base,
      stone: base.stone ? Math.max(8, Math.round(base.stone * 0.8)) : undefined,
    };
  }
  return base;
}

export function canAfford(res: Resources, cost: Partial<Resources>): boolean {
  return (
    res.wood >= (cost.wood || 0) &&
    res.food >= (cost.food || 0) &&
    res.gold >= (cost.gold || 0) &&
    res.stone >= (cost.stone || 0)
  );
}

export function spendResources(res: Resources, cost: Partial<Resources>): void {
  res.wood -= cost.wood || 0;
  res.food -= cost.food || 0;
  res.gold -= cost.gold || 0;
  res.stone -= cost.stone || 0;
}

export function refundResources(res: Resources, cost: Partial<Resources>, ratio = 0.5): void {
  res.wood += Math.round((cost.wood || 0) * ratio);
  res.food += Math.round((cost.food || 0) * ratio);
  res.gold += Math.round((cost.gold || 0) * ratio);
  res.stone += Math.round((cost.stone || 0) * ratio);
}
